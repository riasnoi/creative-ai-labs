#!/usr/bin/env python3
"""ЛР 2. Карточка модели для учебного генератора из ЛР 1 (девять разделов по Mitchell и др., 2018).

Данные берутся из паспорта эксперимента ЛР 1 (passport.json). Поля, которые нельзя вывести из паспорта (лицензия кода,
ответственный), передаются параметрами; если не переданы — в карточке остаются пометки «не указано».

    python lab02_model_card.py --passport ..\\..\\ЛР01_...\\demo_journal\\variant01\\passport.json --out ..\\artifacts\\model_card.md
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

LABELS = {"mean": "среднее", "contrast": "контраст", "edge": "граничная энергия", "entropy": "энтропия, бит"}


def build(p: dict, code_license: str, owner: str) -> str:
    env, res = p.get("среда", {}), p.get("результаты", {})
    par = p.get("параметры", {})
    base = par.get("базовые", {})
    table = ["| Метрика | среднее по серии | s (n−1) |", "|---|---:|---:|"]
    for m, t in res.get("метрики", {}).items():
        table.append(f"| {LABELS.get(m, m)} | {t['mean_base']:.4f} | {t['s_base']:.4f} |".replace(".", ","))
    n = par.get("число_seed", "?")
    lic = code_license or "не указана"
    own = owner or "не указан"
    return "\n".join([
        "# Карточка модели: учебный генератор процедурных текстур", "",
        f"*Формат — по разделам Mitchell и др. (2018). Составлена по паспорту эксперимента ЛР 1 от {p.get('дата', '?')}.*", "",
        "## Model Details (сведения о модели)", "",
        f"* Название и версия: lab01_generator.py, версия {env.get('generator_version', '?')}; контрольные суммы скриптов записаны в паспорте ЛР 1.",
        "* Тип: детерминированный процедурный алгоритм (шум значений с несколькими октавами); **не обучаемая модель**, весов нет.",
        f"* Среда выполнения: Python {env.get('python', '?')} ({env.get('implementation', '?')}), {env.get('platform', '?')}.",
        f"* Лицензия кода: {lic}. Ответственный: {own}.", "",
        "## Intended Use (назначение)", "",
        "* Основное: учебное — отработка воспроизводимости эксперимента (seed, контрольные суммы, паспорт).",
        "* Вне назначения: оценка качества реальных генеративных моделей; выпуск изображений в продуктах; любые задачи, где важна эстетика или безопасность.", "",
        "## Factors (факторы)", "",
        f"* Параметры, влияющие на результат: размер, шаг решётки, число октав, затухание, квантование, интерполяция (базовые значения: {json.dumps(base, ensure_ascii=False)}).",
        "* Группы людей: не применимо — данных о людях нет.", "",
        "## Metrics (метрики)", "",
        "* Среднее, контраст, граничная энергия, энтропия гистограммы; разброс между запусками — выборочное стандартное отклонение по n значениям seed.",
        "* Решение о влиянии фактора — учебный критерий |Δ| > 2s, заданный до эксперимента (не статистический тест).", "",
        "## Evaluation Data (данные для оценки)", "",
        f"* Внешних данных нет: оценка выполнена на серии из {n} изображений, порождённых самим генератором (seed подряд).", "",
        "## Training Data (обучающие данные)", "",
        "* Обучение не выполнялось; обучающих данных нет.", "",
        "## Quantitative Analyses (количественный анализ)", "", *table, "",
        "* Значения — из паспорта ЛР 1; для другого набора seed они будут другими.", "",
        "## Ethical Considerations (этические аспекты)", "",
        "* Персональных данных и материалов третьих лиц нет; результаты синтетические.",
        "* Карточка учебного генератора не заменяет анализ рисков реальных моделей (см. реестр рисков ЛР 2).", "",
        "## Caveats and Recommendations (ограничения и рекомендации)", "",
        f"* Ограничения из паспорта: {p.get('ограничения', 'не указаны')}.",
        "* Рекомендация: при переходе к реальной модели (ЛР 5) добавить в карточку версию весов, лицензию весов, источник и лицензии обучающих данных, если они известны.",
        "* Пробел, выявленный при составлении карточки: " + ("лицензия кода не указана." if lic == "не указана" else "критичных пробелов не выявлено.") ,
    ]) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--passport", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--code-license", default="", help="идентификатор лицензии кода (SPDX), если выбрана")
    ap.add_argument("--owner", default="", help="ответственный за модель")
    a = ap.parse_args()
    p = json.loads(a.passport.read_text(encoding="utf-8"))
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(build(p, a.code_license, a.owner), encoding="utf-8")
    print(f"карточка модели записана: {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
